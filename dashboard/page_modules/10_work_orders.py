    DUR = {"CRITICAL":12,"HIGH":8,"MEDIUM":6,"LOW":4}
    OFFSET = {"CRITICAL":1,"HIGH":12,"MEDIUM":24,"LOW":120}

    for _, row in df_pipeline.iterrows():
        pri    = row.get("priority","LOW")
        color  = PRIORITY_COLOR.get(pri, COLORS["healthy"])
        tid    = row.get("turbine_id","")
        action = row.get("action","").replace("_"," ")
        rul    = float(row.get("rul_hours",80))
        crew   = row.get("assigned_crew","TBD")
        anom   = float(row.get("anomaly_score",0))
        dur    = DUR.get(pri,6)
        oh     = OFFSET.get(pri,24)
        start  = now + timedelta(hours=oh)
        end    = start + timedelta(hours=dur)
        mc     = MAINT_COST.get(pri,5000)
        cf     = 0.40 + min(rul/125.0,1.0)*0.25
        loss   = round(2000*cf*dur*0.075, 2)
        ns     = round(50000-mc-loss, 2)

        emoji = {"CRITICAL":"🚨","HIGH":"⚠️","MEDIUM":"📋","LOW":"✅"}.get(pri,"📋")

        try:
            r,g,b = int(color[1:3],16), int(color[3:5],16), int(color[5:7],16)
            glow  = f"rgba({r},{g},{b},0.08)"
            bdr   = f"rgba({r},{g},{b},0.22)"
        except Exception:
            glow = "rgba(0,212,255,0.08)"; bdr = COLORS["border"]

        with st.expander(f"{emoji} **{tid}** — {pri} — {action}", expanded=(pri=="CRITICAL")):
            m1,m2,m3,m4,m5 = st.columns(5)
            m1.metric("RUL",          f"{rul:.0f}h")
            m2.metric("Duration",     f"{dur}h")
            m3.metric("Anomaly",      f"{anom:.3f}")
            m4.metric("Revenue Loss", f"${loss:,.0f}")
            m5.metric("Net Saving",   f"${ns:,.0f}")

            st.markdown(
                '<div style="display:flex;gap:8px;flex-wrap:wrap;margin:12px 0 10px;">'
                + priority_badge(pri) +
                '<span class="ws-badge ws-badge-cyan">👷 ' + str(crew) + '</span>'
                '<span class="ws-badge ws-badge-gray">🕐 ' + start.strftime("%b %d %H:%M") + '</span>'
                '<span class="ws-badge ws-badge-gray">🕐 ' + end.strftime("%b %d %H:%M") + '</span>'
                '<span class="ws-badge ws-badge-gray">⏱️ ' + str(dur) + 'h window</span>'
                '</div>',
                unsafe_allow_html=True
            )

            # Work order summary box
            st.markdown(
                '<div style="background:rgba(5,8,22,0.85);'
                'border:1px solid ' + bdr + ';'
                'border-left:3px solid ' + color + ';'
                'border-radius:12px;padding:16px 18px;'
                'margin-top:10px;margin-bottom:10px;">'
                '<div style="font-size:9px;color:' + color + ';font-weight:700;'
                'letter-spacing:1.5px;margin-bottom:10px;">📋 WORK ORDER SUMMARY</div>'
                '<div style="display:grid;grid-template-columns:1fr 1fr;gap:8px;">'
                '<div style="font-size:12px;color:' + COLORS["text_secondary"] + ';">'
                '<b style="color:' + COLORS["text_muted"] + ';">Asset:</b> ' + tid + '</div>'
                '<div style="font-size:12px;color:' + COLORS["text_secondary"] + ';">'
                '<b style="color:' + COLORS["text_muted"] + ';">Priority:</b> ' + pri + '</div>'
                '<div style="font-size:12px;color:' + COLORS["text_secondary"] + ';">'
                '<b style="color:' + COLORS["text_muted"] + ';">Action:</b> ' + action + '</div>'
                '<div style="font-size:12px;color:' + COLORS["text_secondary"] + ';">'
                '<b style="color:' + COLORS["text_muted"] + ';">Crew:</b> ' + str(crew) + '</div>'
                '<div style="font-size:12px;color:' + COLORS["text_secondary"] + ';">'
                '<b style="color:' + COLORS["text_muted"] + ';">Scheduled:</b> ' + start.strftime("%b %d, %Y %H:%M") + '</div>'
                '<div style="font-size:12px;color:' + COLORS["text_secondary"] + ';">'
                '<b style="color:' + COLORS["text_muted"] + ';">Est. Cost:</b> $' + f"{mc:,}" + '</div>'
                '</div>'
                '<div style="margin-top:10px;padding-top:10px;'
                'border-top:1px solid rgba(255,255,255,0.05);'
                'font-size:12px;color:' + COLORS["text_secondary"] + ';line-height:1.7;">'
                'Net saving vs unplanned failure: '
                '<span style="color:' + COLORS["healthy"] + ';font-weight:700;'
                "font-family:'JetBrains Mono',monospace;\">$" + f"{ns:,.0f}" + '</span>'
                ' &nbsp;·&nbsp; '
                '$50,000 failure avoided − $' + f"{mc:,}" + ' maintenance − $' + f"{loss:,.0f}" + ' generation loss'
                '</div></div>',
                unsafe_allow_html=True
            )

    # Export all as CSV
    st.markdown("<div style='height:16px;'></div>", unsafe_allow_html=True)
    rows = []
    for _, row in df_pipeline.iterrows():
        pri = row.get("priority","LOW")
        rul = float(row.get("rul_hours",80))
        dur = DUR.get(pri,6); oh = OFFSET.get(pri,24)
        start = now + timedelta(hours=oh)
        mc = MAINT_COST.get(pri,5000)
        cf = 0.40+min(rul/125.0,1.0)*0.25
        loss = round(2000*cf*dur*0.075,2)
        ns = round(50000-mc-loss,2)
        rows.append({
            "Turbine": row.get("turbine_id",""),
            "Priority": pri,
            "Action": row.get("action","").replace("_"," "),
            "Crew": row.get("assigned_crew",""),
            "Scheduled Start": start.strftime("%Y-%m-%d %H:%M"),
            "Duration (h)": dur,
            "RUL (h)": round(rul,1),
            "Anomaly Score": round(float(row.get("anomaly_score",0)),3),
            "Maint Cost ($)": mc,
            "Revenue Loss ($)": loss,
            "Net Saving ($)": ns,
        })
    if rows:
        export_df = pd.DataFrame(rows)
        st.dataframe(export_df, use_container_width=True, hide_index=True,
                     column_config={
                         "Maint Cost ($)":   st.column_config.NumberColumn(format="$%.0f"),
                         "Revenue Loss ($)": st.column_config.NumberColumn(format="$%.0f"),
                         "Net Saving ($)":   st.column_config.NumberColumn(format="$%.0f"),
                     })
        st.download_button("⬇️ Export All Work Orders CSV",
                           export_df.to_csv(index=False),
                           "work_orders.csv","text/csv",
                           use_container_width=False)

